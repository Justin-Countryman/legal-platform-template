#!/usr/bin/env node
// compare-builds — are two builds' prerendered pages the same page?
//
//   node scripts/ci/compare-builds.mjs <baseline dir> <candidate dir>
//
// Each dir is a copy of a build's `.next/server/app` with its `BUILD_ID` beside it
// (`<dir>/app/**` and `<dir>/BUILD_ID`). Exit 0 when every prerendered `.html` and
// `.rsc` in the baseline has a candidate twin that matches after exactly three
// normalizations, each printed so nobody has to trust this header:
//
//   1. the build id, which differs on every build;
//   2. the file names under `/_next/static/chunks/`, which the bundler renames when
//      the module graph changes anywhere, even for byte-identical pages;
//   3. the ORDER of the flight rows (the RSC payload, whether in a `.rsc` file or in
//      the HTML's `self.__next_f.push` scripts), compared as a sorted multiset,
//      because two builds of unchanged source already emit them in different
//      orders (measured, monorepo WS-V1-PHASE17A-DESIGN §7.5).
//
// Written for Phase 17A's split of the site layout and the homepage into
// `SiteShell` and `HomeBody`: a move that must change nothing a visitor receives.
// It is a local proof, run by hand on two builds; it is not a CI gate, because a
// committed baseline would have to be regenerated by every change to any page.

import {readFileSync, readdirSync, statSync, existsSync} from 'node:fs'
import {join, relative} from 'node:path'

const [baseDir, candDir] = process.argv.slice(2)
if (!baseDir || !candDir) {
  console.error('usage: compare-builds.mjs <baseline dir> <candidate dir>')
  process.exit(2)
}

const buildId = (dir) => readFileSync(join(dir, 'BUILD_ID'), 'utf8').trim()
const ids = [buildId(baseDir), buildId(candDir)]

function walk(dir) {
  const out = []
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) out.push(...walk(p))
    else if (p.endsWith('.html') || p.endsWith('.rsc')) out.push(p)
  }
  return out
}

function flightFromHtml(html) {
  const rows = []
  const re = /<script>self\.__next_f\.push\((\[[\s\S]*?\])\)<\/script>/g
  let payload = ''
  const rest = html.replace(re, (_, arr) => {
    const [kind, str] = JSON.parse(arr)
    if (kind === 1 && typeof str === 'string') payload += str
    return '<script data-flight></script>'
  })
  for (const line of payload.split('\n')) if (line) rows.push(line)
  return {rest, rows}
}

function normalize(text, id) {
  return text
    .split(id).join('<BUILD_ID>')
    .replace(/\/_next\/static\/chunks\/[A-Za-z0-9_\-./~]+?\.(js|css)/g, '/_next/static/chunks/<CHUNK>.$1')
    .replace(/static\/chunks\/[A-Za-z0-9_\-./~]+?\.(js|css)/g, 'static/chunks/<CHUNK>.$1')
}

const sortRows = (rows) => [...rows].sort()

let compared = 0
const failures = []
for (const file of walk(join(baseDir, 'app'))) {
  const rel = relative(join(baseDir, 'app'), file)
  const twin = join(candDir, 'app', rel)
  if (!existsSync(twin)) {
    failures.push(`${rel}: missing from the candidate build`)
    continue
  }
  const a = normalize(readFileSync(file, 'utf8'), ids[0])
  const b = normalize(readFileSync(twin, 'utf8'), ids[1])
  compared++
  if (file.endsWith('.rsc')) {
    const ra = sortRows(a.split('\n').filter(Boolean))
    const rb = sortRows(b.split('\n').filter(Boolean))
    if (JSON.stringify(ra) !== JSON.stringify(rb)) failures.push(`${rel}: flight rows differ`)
    continue
  }
  const fa = flightFromHtml(a)
  const fb = flightFromHtml(b)
  if (fa.rest !== fb.rest) failures.push(`${rel}: HTML outside the flight payload differs`)
  else if (JSON.stringify(sortRows(fa.rows)) !== JSON.stringify(sortRows(fb.rows))) failures.push(`${rel}: flight rows differ`)
}

console.log('compare-builds: normalized (1) the build id, (2) /_next/static/chunks/ file names, (3) flight-row order.')
console.log(`compare-builds: ${compared} prerendered file(s) compared, ${failures.length} differ.`)
for (const f of failures) console.log(`  DIFFERS  ${f}`)
process.exit(failures.length ? 1 : 0)
